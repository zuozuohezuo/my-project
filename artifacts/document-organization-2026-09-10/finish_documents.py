    index = relative(path, 'docs/README.md')
    if '/90_归档/' in path:
        role = '历史归档：保留当时方案与上下文，不作为当前实现依据。'
    elif '/03_试玩与验收/' in path:
        if '验收' in Path(path).name:
            role = '版本验收记录：正文结论只适用于记录日期与当时版本，保留原数值。'
        else:
            role = '当前试玩说明：操作、演示数据和限制以正文标注版本为准。'
    elif '/04_历史研究/' in path:
        role = '历史研究资料：用于查证和设计参考，不表示已纳入运行模拟。'
